#!/usr/bin/env node
/* Bake canonical JSON into the file:// fallback consumed by Android/WebView. */
"use strict";

var fs = require("fs");
var path = require("path");
var root = path.join(__dirname, "..");
var dataDir = path.join(root, "data");

function read(rel) {
  return JSON.parse(fs.readFileSync(path.join(dataDir, rel), "utf8"));
}

var levels = {};
fs.readdirSync(path.join(dataDir, "levels")).filter(function (name) {
  return /\.json$/.test(name);
}).sort().forEach(function (name) {
  levels[path.basename(name, ".json")] = read(path.join("levels", name));
});

var raw = {
  moves: read("moves.json"),
  enemies: read("enemies.json"),
  strings: read("strings.ru.json"),
  campaign: read("campaign.json"),
  audio: read("audio.json"),
  levels: levels
};
var body = "/* GENERATED by tools/build-data-index.js — do not hand-edit. */\n" +
  "(function () {\n  var raw = " + JSON.stringify(raw) + ";\n" +
  "  if (typeof window !== \"undefined\") window.PDataRaw = raw;\n" +
  "  if (typeof global !== \"undefined\") global.PDataRaw = raw;\n" +
  "  if (typeof module !== \"undefined\" && module.exports) module.exports = raw;\n" +
  "})();\n";
fs.writeFileSync(path.join(dataDir, "index.js"), body);
console.log("baked " + Object.keys(levels).length + " levels to data/index.js");
